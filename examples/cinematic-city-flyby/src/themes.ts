/** A look for the whole scene: the map's colours, its sky and labels, the buildings and their light, and the effects over the frame. */
export type FlybyTheme = {
    label: string;
    /** The heading the theme is listed under; the themes come grouped, the most natural looks first. */
    group: 'Natural light' | 'Camera and film' | 'Print and paper' | 'Neon and night';
    style: StandardStyleID;
    /** The colours the map's ten are derived from. */
    theme: { colors: string[]; mode: MapThemeMode };
    /** The sky overhead, and a glow towards the horizon; the horizon itself fades into the map's land. */
    sky: { color: string; horizon?: string };
    /** The open source typeface the map's labels are set in. */
    font: CustomTypeface;
    buildings: Buildings3DConfig;
    landmarks: Landmarks3DConfig;
    effects: MapEffectsConfig;
    /** A stylisation of the frame, run inside the effects' own chain so the bloom and grade read it. */
    pass?: MapEffectsPass;
};

// One family from Fontsource: its regular weight and bold, and its italic where it has one.
const fontsource = (
    family: string,
    { regular = 400, bold = 700, italic = true }: { regular?: number; bold?: number | false; italic?: boolean } = {},
) => {
    const file = (weight: number, style: 'normal' | 'italic') =>
        `https://cdn.jsdelivr.net/fontsource/fonts/${family}@latest/latin-${weight}-${style}.woff2`;
    const typeface: CustomTypeface = { regular: file(regular, 'normal') };
    if (bold) typeface.bold = file(bold, 'normal');
    if (italic) typeface.regularItalic = file(regular, 'italic');
    return typeface;
};

